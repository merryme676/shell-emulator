#!/usr/bin/env bash
# ↑ Шебанг: говорит системе, что это bash-скрипт.
#   Если файл исполняемый (chmod +x), можно запускать ./run.sh

#
# Скрипт запуска эмулятора shell.
#
# Использование:
#   ./run.sh                    — запустить эмулятор
#   ./run.sh --vfs path.xml     — запустить с указанием VFS (Этап 2)
#

# Строгий режим bash — три опции:
#   -e            : падать сразу, если команда вернула ошибку
#   -u            : ругаться на неопределённые переменные
#   -o pipefail   : падать, если любая команда в цепочке упала
set -euo pipefail

# Определяем директорию, где лежит сам run.sh.
# BASH_SOURCE[0] — путь к текущему скрипту.
# dirname — берёт папку без имени файла.
# cd ... && pwd — переходим в папку и получаем абсолютный путь.
# Зачем: чтобы ./run.sh работал из любой папки.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Запускаем Python-скрипт с полным путём.
# ${SCRIPT_DIR}/src/main.py — путь к нашему эмулятору.
# "$@" — все аргументы, переданные в run.sh.
#   Например: ./run.sh --vfs vfs.xml
#   Тогда "$@" = --vfs vfs.xml
#   И они попадут в main.py.
python3 "${SCRIPT_DIR}/src/main.py" "$@"
